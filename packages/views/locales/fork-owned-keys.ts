/**
 * Whether an EN key (plural suffixes normalized, dot-separated path) belongs to
 * a surface the fork owns rather than to upstream.
 */
export function isForkOwnedKey(namespace: string, key: string): boolean {
  const prefixes = FORK_OWNED_PREFIXES[namespace];
  if (prefixes === undefined) return false;
  if (prefixes.length === 0) return true;
  return prefixes.some(
    (prefix) => key === prefix || key.startsWith(prefix + "."),
  );
}

/** Whether every EN key in a namespace is fork-owned. */
export function isForkOwnedNamespace(
  namespace: string,
  keys: readonly string[],
): boolean {
  return keys.length > 0 && keys.every((key) => isForkOwnedKey(namespace, key));
}

