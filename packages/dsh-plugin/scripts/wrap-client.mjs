import { readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Turn Vite's CommonJS output into a dsh client artifact.
 *
 * dsh's module system expects every browser plugin to register itself with
 * `window.__ModuleLoader__.load({ id, factory })`, where the factory receives
 * the shell's `require`. That `require` is the only bridge across the React
 * boundary: the wrapper asks for the shell's React and hands it to the plugin,
 * so the seat element is branded for the React that renders it while the island
 * below it keeps its own bundled React 19.
 */

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packageJson = JSON.parse(
  await readFile(join(packageRoot, "package.json"), "utf8"),
);
const id = packageJson.name;

const bundlePath = join(packageRoot, "lib/client.bundle.cjs");
const bundle = await readFile(bundlePath, "utf8");

const artifact = `/* ${id} — generated by scripts/wrap-client.mjs. Do not edit. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(id)},
  factory: function (require) {
    var module = { exports: {} };
    var exports = module.exports;
    var hostReact = null;
    try {
      hostReact = typeof require === "function" ? require("react") : null;
    } catch (error) {
      // A shell with no React row: fall through to the bundled copy below.
      hostReact = null;
    }
${indent(bundle)}
    var api = module.exports;
    if (api.configureHostRuntime) {
      api.configureHostRuntime(hostReact && hostReact.createElement ? hostReact.createElement : null);
    }
    api.default = api;
    return api;
  },
});
`;

await writeFile(join(packageRoot, "lib/client.js"), artifact, "utf8");
await rm(bundlePath, { force: true });
await rm(join(packageRoot, "lib/client.bundle.css"), { force: true });

function indent(source) {
  return source
    .split("\n")
    .map((line) => (line === "" ? line : `    ${line}`))
    .join("\n");
}
