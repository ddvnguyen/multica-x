#!/usr/bin/env bash
# deploy/dsh-z/deploy.sh — provision and update the isolated lane z topology.
#
# Builds and runs, everything loopback-only on the lane host:
#   multica-be z  (Go server from multica-x @ MULTICA_X_REF) on MULTICA_BE_Z_PORT
#   Postgres      role+db `multica_z` on the existing :5432 cluster (additive)
#   moct-be z     (Paseo fleet backend @ MOCT_REF) on MOCT_BE_Z_PORT, own Turso
#   lane-z daemon (multica CLI profile `z` under LANE_HOME; dsh runtime only
#                 when DSH_Z_RUNTIME_BUNDLE points at a bundle source)
#
# Idempotent: every phase re-runs cleanly; releases are keyed by commit sha and
# reused when already built. The script only manages ITS OWN systemd user units
# (multica-be-z, moct-backend-z, multica-daemon-z) and only ADDs the role and
# database on the shared Postgres cluster. It never kills any process by PID
# and never touches the live control plane (multica_backend_1, multica-*,
# dsh-x, dsh-z, moct-backend, moct-x units/containers).
#
# Usage: bash deploy/dsh-z/deploy.sh   (run from anywhere; reads dsh-z.env)

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=dsh-z.env
source "$SCRIPT_DIR/dsh-z.env"

log()  { printf '[lane-z] %s\n' "$*"; }
die()  { printf '[lane-z] ERROR: %s\n' "$*" >&2; exit 1; }
need() { command -v "$1" >/dev/null 2>&1 || die "missing dependency: $1"; }

need git; need node; need curl; need podman; need pnpm; need openssl

# ---------------------------------------------------------------------------
# Phase 0 — preflight
# ---------------------------------------------------------------------------
log "phase 0: preflight"

# A lane port may be taken by our own already-running unit (idempotent rerun);
# anything else on it means the port is gone — fail loudly instead of rebinding.
check_port() { # $1=port $2=our-unit
  case "$1" in
    3080|3081|3180|3181|3702|3703|4320|5432|8099|8100|8110|8210)
      die "refusing protected port $1" ;;
  esac
  if ss -tln 2>/dev/null | awk '{print $4}' | grep -qE ":$1$"; then
    if systemctl --user is-active --quiet "$2" 2>/dev/null; then
      log "port $1 already served by $2 (rerun)"
    else
      die "port $1 is already in use and $2 is not running; pick another in deploy/dsh-z/dsh-z.env"
    fi
  fi
}
check_port "$MULTICA_BE_Z_PORT" "$MULTICA_BE_Z_UNIT"
check_port "$MOCT_BE_Z_PORT" "$MOCT_BE_Z_UNIT"

podman ps --format '{{.Names}}' 2>/dev/null | grep -qx "$MULTICA_Z_DB_CONTAINER" \
  || die "postgres container '$MULTICA_Z_DB_CONTAINER' is not running"

mkdir -p "$LANE_ROOT/data" "$LANE_ROOT/src" "$LANE_ROOT/logs"
mkdir -p "$LANE_ROOT/multica-be/releases" "$LANE_ROOT/multica-be"
mkdir -p "$MOCT_Z_ROOT/releases" "$MOCT_Z_ROOT/data" "$MOCT_Z_STATE_DIR" "$MOCT_Z_BACKUP_DIR"
mkdir -p "$LANE_HOME" "$MULTICA_Z_WORKSPACES_ROOT"
chmod 700 "$LANE_HOME"

# ---------------------------------------------------------------------------
# Phase 1 — runtime secrets (generated once, 0600, never committed)
# ---------------------------------------------------------------------------
log "phase 1: runtime env $LANE_RUNTIME_ENV"

if [ ! -f "$LANE_RUNTIME_ENV" ]; then
  umask 077
  {
    echo "# lane z runtime secrets — generated by deploy/dsh-z/deploy.sh"
    echo "MULTICA_Z_DB_PASSWORD=lz$(openssl rand -hex 16)"
    echo "MULTICA_Z_JWT_SECRET=$(openssl rand -hex 32)"
    echo "MULTICA_Z_DEV_CODE=$(printf '%06d' "$((RANDOM % 1000000))")"
    echo "MULTICA_Z_ADMIN_EMAIL=$MULTICA_Z_ADMIN_EMAIL"
  } > "$LANE_RUNTIME_ENV"
  umask 022
fi
chmod 600 "$LANE_RUNTIME_ENV"
# shellcheck source=/dev/null
source "$LANE_RUNTIME_ENV"

MULTICA_Z_DATABASE_URL="${MULTICA_Z_DSN_TEMPLATE/PASSWORD/$MULTICA_Z_DB_PASSWORD}"

# ---------------------------------------------------------------------------
# Phase 2 — Postgres role + database (additive, idempotent)
# ---------------------------------------------------------------------------
log "phase 2: postgres role/db $MULTICA_Z_DB_ROLE/$MULTICA_Z_DB_NAME on :$MULTICA_Z_DB_PORT"

PW_ESC=${MULTICA_Z_DB_PASSWORD//\'/\'\'}
printf "DO \$\$ BEGIN\n  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname='%s') THEN\n    CREATE ROLE %s LOGIN PASSWORD '%s';\n  ELSE\n    ALTER ROLE %s WITH LOGIN PASSWORD '%s';\n  END IF;\nEND \$\$;\n" \
  "$MULTICA_Z_DB_ROLE" "$MULTICA_Z_DB_ROLE" "$PW_ESC" "$MULTICA_Z_DB_ROLE" "$PW_ESC" \
  | podman exec -i "$MULTICA_Z_DB_CONTAINER" psql -U hydra -d postgres -v ON_ERROR_STOP=1 >/dev/null

if ! podman exec -i "$MULTICA_Z_DB_CONTAINER" psql -U hydra -d postgres -tAc \
  "SELECT 1 FROM pg_database WHERE datname='$MULTICA_Z_DB_NAME'" | grep -q 1; then
  podman exec "$MULTICA_Z_DB_CONTAINER" psql -U hydra -d postgres \
    -c "CREATE DATABASE \"$MULTICA_Z_DB_NAME\" OWNER \"$MULTICA_Z_DB_ROLE\""
fi

# ---------------------------------------------------------------------------
# Phase 3 — multica-be release (server + migrate + lane CLI)
# ---------------------------------------------------------------------------
log "phase 3: multica-be release from $MULTICA_X_REPO @ $MULTICA_X_REF"

MC_SRC="$LANE_ROOT/src/multica-x"
if [ ! -d "$MC_SRC/.git" ]; then
  git clone "$MULTICA_X_REPO" "$MC_SRC"
fi
git -C "$MC_SRC" fetch origin "$MULTICA_X_REF" --tags >/dev/null 2>&1 || true
MC_SHA="$(git -C "$MC_SRC" rev-parse "origin/$MULTICA_X_REF")"
git -C "$MC_SRC" checkout -q --detach "$MC_SHA"
log "multica-be sha: $MC_SHA"

MC_REL="$LANE_ROOT/multica-be/releases/$MC_SHA"
if [ ! -f "$MC_REL/.complete" ]; then
  rm -rf "$MC_REL"; mkdir -p "$MC_REL/bin"
  GO_BIN="${MULTICA_GO:-}"
  if [ -z "$GO_BIN" ]; then
    if command -v go >/dev/null 2>&1; then GO_BIN="$(command -v go)"
    elif [ -x /mnt/workspace/tmp/spike-tools/go-sdk/bin/go ]; then GO_BIN=/mnt/workspace/tmp/spike-tools/go-sdk/bin/go
    else die "no Go toolchain found (set MULTICA_GO=/path/to/go; no 'go' on the lane PATH by design)"; fi
  fi
  log "building multica-be with $GO_BIN"
  (
    cd "$MC_SRC/server"
    GOFLAGS=-mod=mod \
    GOMODCACHE="${MULTICA_GOMODCACHE:-/mnt/workspace/tmp/go/mod}" \
    GOPATH="${MULTICA_GOPATH:-/mnt/workspace/tmp/go}" \
    "$GO_BIN" build -ldflags "-X main.version=v0.6.5-lanez -X main.commit=$MC_SHA" -o "$MC_REL/bin/server"  ./cmd/server
    GOFLAGS=-mod=mod \
    GOMODCACHE="${MULTICA_GOMODCACHE:-/mnt/workspace/tmp/go/mod}" \
    GOPATH="${MULTICA_GOPATH:-/mnt/workspace/tmp/go}" \
    "$GO_BIN" build -o "$MC_REL/bin/migrate" ./cmd/migrate
    GOFLAGS=-mod=mod \
    GOMODCACHE="${MULTICA_GOMODCACHE:-/mnt/workspace/tmp/go/mod}" \
    GOPATH="${MULTICA_GOPATH:-/mnt/workspace/tmp/go}" \
    "$GO_BIN" build -ldflags "-X main.version=v0.6.5-lanez -X main.commit=$MC_SHA" -o "$MC_REL/bin/multica" ./cmd/multica
  )
  # Self-contained release: migrate resolves ./migrations from its CWD, so the
  # release carries its own copy and never needs the source checkout at runtime.
  cp -a "$MC_SRC/server/migrations" "$MC_REL/migrations"
  printf '{"sha":"%s","ref":"%s","builtAt":"%s"}\n' "$MC_SHA" "$MULTICA_X_REF" "$(date -u +%Y-%m-%dT%H:%M:%SZ)" > "$MC_REL/release.json"
  : > "$MC_REL/.complete"
  log "packaged $MC_REL"
else
  log "release already built, reusing $MC_REL"
fi
ln -sfn "$MC_REL" "$LANE_ROOT/multica-be/current"

# Server env file (0600): consumed by the unit via EnvironmentFile.
umask 077
{
  echo "PORT=$MULTICA_BE_Z_PORT"
  echo "MULTICA_BIND_HOST=$MULTICA_BE_Z_BIND_HOST"
  echo "DATABASE_URL=$MULTICA_Z_DATABASE_URL"
  echo "JWT_SECRET=$MULTICA_Z_JWT_SECRET"
  echo "MULTICA_PUBLIC_URL=$MULTICA_BE_Z_PUBLIC_URL"
  # Lane auth bootstrap: fixed dev verification code; never set in production.
  echo "MULTICA_DEV_VERIFICATION_CODE=$MULTICA_Z_DEV_CODE"
} > "$LANE_ROOT/multica-be/env"
umask 022

# ---------------------------------------------------------------------------
# Phase 4 — migrations
# ---------------------------------------------------------------------------
log "phase 4: migrate up on $MULTICA_Z_DB_NAME"

( cd "$MC_REL" && DATABASE_URL="$MULTICA_Z_DATABASE_URL" "$MC_REL/bin/migrate" up )

# ---------------------------------------------------------------------------
# Phase 5 — moct-be z release
# ---------------------------------------------------------------------------
log "phase 5: moct-be z release from $MOCT_REPO @ $MOCT_REF"

MOCT_SRC="$LANE_ROOT/src/moct"
if [ ! -d "$MOCT_SRC/.git" ]; then
  git clone "$MOCT_REPO" "$MOCT_SRC"
fi
git -C "$MOCT_SRC" fetch origin "$MOCT_REF" >/dev/null 2>&1 || true
MOCT_SHA="$(git -C "$MOCT_SRC" rev-parse "origin/$MOCT_REF")"
git -C "$MOCT_SRC" checkout -q --detach "$MOCT_SHA"
log "moct-be sha: $MOCT_SHA"

if [ ! -f "$MOCT_SRC/dist/daemon.js" ]; then
  ( cd "$MOCT_SRC" && pnpm install --frozen-lockfile --prefer-offline >/dev/null && pnpm run build >/dev/null )
fi

MOCT_REL="$MOCT_Z_ROOT/releases/$MOCT_SHA"
if [ ! -f "$MOCT_REL/.complete" ]; then
  rm -rf "$MOCT_REL"; mkdir -p "$MOCT_REL"
  cp -a "$MOCT_SRC/dist" "$MOCT_REL/dist"
  cp -a "$MOCT_SRC/package.json" "$MOCT_REL/package.json"
  # Hardlink, never copy: the shared pnpm store holds every file already.
  cp -al "$MOCT_SRC/node_modules" "$MOCT_REL/node_modules"
  sed -i "s/number: \"dev\"/number: \"${MOCT_SHA:0:7}\"/; s/date: \"unknown\"/date: \"$(date -u +%Y-%m-%dT%H:%M:%SZ)\"/; s/git_sha: \"unknown\"/git_sha: \"$MOCT_SHA\"/" \
    "$MOCT_REL/dist/surfaces/http/health.js"
  grep -q "git_sha: \"$MOCT_SHA\"" "$MOCT_REL/dist/surfaces/http/health.js" || die "moct BUILD_INFO rewrite failed"
  printf '{"sha":"%s","ref":"%s","version":"%s","packagedAt":"%s"}\n' \
    "$MOCT_SHA" "$MOCT_REF" "$(node -p "require('$MOCT_REL/package.json').version")" "$(date -u +%Y-%m-%dT%H:%M:%SZ)" \
    > "$MOCT_REL/release.json"
  : > "$MOCT_REL/.complete"
  log "packaged $MOCT_REL"
else
  log "release already built, reusing $MOCT_REL"
fi
ln -sfn "$MOCT_REL" "$MOCT_Z_ROOT/current"

umask 077
{
  echo "ORCHESTRATION_BIND=127.0.0.1"
  echo "ORCHESTRATION_PORT=$MOCT_BE_Z_PORT"
  echo "FLEET_DB_PATH=$MOCT_Z_DB_PATH"
  echo "MCP_ORCH_STATE_DIR=$MOCT_Z_STATE_DIR"
  echo "MOCT_BACKUP_DIR=$MOCT_Z_BACKUP_DIR"
} > "$MOCT_Z_ROOT/env"
umask 022

# ---------------------------------------------------------------------------
# Phase 6 — systemd user units
# ---------------------------------------------------------------------------
log "phase 6: systemd user units"

UNIT_DIR="$HOME/.config/systemd/user"
install_unit() { # $1=template $2=target $3..=substitutions (NAME=VALUE)
  local tmpl="$SCRIPT_DIR/units/$1" out="$UNIT_DIR/$2" tmp
  tmp="$UNIT_DIR/.$2.tmp"
  cp "$tmpl" "$tmp"
  local kv; shift 2
  for kv in "$@"; do
    sed -i "s|__${kv%%=*}__|${kv#*=}|g" "$tmp"
  done
  grep -q "__[A-Z_]*__" "$tmp" && die "unsubstituted placeholder in $2"
  mv "$tmp" "$out"; chmod 600 "$out"
}

mkdir -p "$UNIT_DIR"
install_unit multica-be-z.service "$MULTICA_BE_Z_UNIT" \
  "RELEASE_DIR=$MC_REL" \
  "SERVER_ENV=$LANE_ROOT/multica-be/env"
install_unit moct-backend-z.service "$MOCT_BE_Z_UNIT" \
  "MOCT_ROOT=$MOCT_Z_ROOT" \
  "MOCT_ENV=$MOCT_Z_ROOT/env"
install_unit multica-daemon-z.service "$MULTICA_DAEMON_Z_UNIT" \
  "LANE_HOME=$LANE_HOME" \
  "RELEASE_DIR=$LANE_ROOT/multica-be" \
  "DAEMON_ENV=$LANE_ROOT/data/multica-daemon-z.env"

umask 077
{
  echo "MULTICA_WORKSPACES_ROOT=$MULTICA_Z_WORKSPACES_ROOT"
  echo "MULTICA_WORKSPACE_ID=${MULTICA_Z_WORKSPACE_ID:-}"
} > "$LANE_ROOT/data/multica-daemon-z.env"
umask 022

systemctl --user daemon-reload

# ---------------------------------------------------------------------------
# Phase 7 — start backends, wait for readiness
# ---------------------------------------------------------------------------
log "phase 7: start $MULTICA_BE_Z_UNIT and $MOCT_BE_Z_UNIT"

systemctl --user enable --now "$MULTICA_BE_Z_UNIT" "$MOCT_BE_Z_UNIT" >/dev/null 2>&1 || true
systemctl --user restart "$MULTICA_BE_Z_UNIT" "$MOCT_BE_Z_UNIT"

wait_http() { # $1=url $2=timeout-seconds $3=grep-expect (optional)
  local deadline=$((SECONDS + $2)) body code
  while [ "$SECONDS" -lt "$deadline" ]; do
    body="$(curl -fsS --max-time 3 "$1" 2>/dev/null || true)"
    code="$(curl -s -o /dev/null -w '%{http_code}' --max-time 3 "$1" 2>/dev/null || true)"
    if [ "$code" = "200" ] && { [ -z "${3:-}" ] || printf '%s' "$body" | grep -q "$3"; }; then
      return 0
    fi
    sleep 2
  done
  return 1
}

wait_http "http://127.0.0.1:$MULTICA_BE_Z_PORT/healthz" 180 '"status":"ok"' \
  || { journalctl --user -u "$MULTICA_BE_Z_UNIT" -n 40 --no-pager >&2; die "multica-be z /healthz not ok"; }
log "multica-be z ready on http://127.0.0.1:$MULTICA_BE_Z_PORT (healthz ok)"

wait_http "http://127.0.0.1:$MOCT_BE_Z_PORT/health" 60 '"ok":true' \
  || { journalctl --user -u "$MOCT_BE_Z_UNIT" -n 40 --no-pager >&2; die "moct-be z /health not ok"; }
log "moct-be z ready on http://127.0.0.1:$MOCT_BE_Z_PORT"

# ---------------------------------------------------------------------------
# Phase 8 — auth bootstrap: session JWT, PAT, workspace
# ---------------------------------------------------------------------------
log "phase 8: auth + workspace bootstrap"

MC_URL="http://127.0.0.1:$MULTICA_BE_Z_PORT"

if [ -z "${MULTICA_Z_PAT:-}" ] || ! curl -fsS -H "Authorization: Bearer $MULTICA_Z_PAT" "$MC_URL/api/me" >/dev/null 2>&1; then
  # The email send step may fail on a lane (no SMTP) — the verification row is
  # already persisted by then, and the dev code path accepts it without SMTP.
  curl -s -o /dev/null -X POST -H 'Content-Type: application/json' \
    -d "{\"email\":\"$MULTICA_Z_ADMIN_EMAIL\"}" "$MC_URL/auth/send-code" || true
  sleep 1
  SESSION_TOKEN="$(curl -fsS -X POST -H 'Content-Type: application/json' \
    -d "{\"email\":\"$MULTICA_Z_ADMIN_EMAIL\",\"code\":\"$MULTICA_Z_DEV_CODE\"}" \
    "$MC_URL/auth/verify-code" | node -e 'let d="";process.stdin.on("data",c=>d+=c).on("end",()=>console.log(JSON.parse(d).token))')"
  [ -n "$SESSION_TOKEN" ] || die "verify-code did not return a session token"
  MULTICA_Z_PAT="$(curl -fsS -X POST -H "Authorization: Bearer $SESSION_TOKEN" \
    -H 'Content-Type: application/json' -d '{"name":"lane-z-daemon"}' "$MC_URL/api/tokens" \
    | node -e 'let d="";process.stdin.on("data",c=>d+=c).on("end",()=>console.log(JSON.parse(d).token))')"
  [ -n "$MULTICA_Z_PAT" ] || die "PAT creation failed"
  sed -i '/^MULTICA_Z_PAT=/d' "$LANE_RUNTIME_ENV"
  printf 'MULTICA_Z_PAT=%s\n' "$MULTICA_Z_PAT" >> "$LANE_RUNTIME_ENV"
  log "minted lane PAT into $LANE_RUNTIME_ENV"
fi

if [ -z "${MULTICA_Z_WORKSPACE_ID:-}" ]; then
  MULTICA_Z_WORKSPACE_ID="$(curl -fsS -H "Authorization: Bearer $MULTICA_Z_PAT" "$MC_URL/api/workspaces" \
    | node -e 'let d="";process.stdin.on("data",c=>d+=c).on("end",()=>{const w=JSON.parse(d);const hit=(w.workspaces||w).find(x=>x.slug===process.argv[1]);console.log(hit?hit.id:"")})' "$MULTICA_Z_WS_SLUG" 2>/dev/null || true)"
  if [ -z "$MULTICA_Z_WORKSPACE_ID" ]; then
    MULTICA_Z_WORKSPACE_ID="$(curl -fsS -X POST -H "Authorization: Bearer $MULTICA_Z_PAT" \
      -H 'Content-Type: application/json' -d "{\"name\":\"DSH Z\",\"slug\":\"$MULTICA_Z_WS_SLUG\"}" \
      "$MC_URL/api/workspaces" \
      | node -e 'let d="";process.stdin.on("data",c=>d+=c).on("end",()=>{const r=JSON.parse(d);console.log((r.workspace||r).id)})')"
  fi
  [ -n "$MULTICA_Z_WORKSPACE_ID" ] || die "workspace bootstrap failed"
  sed -i '/^MULTICA_Z_WORKSPACE_ID=/d' "$LANE_RUNTIME_ENV"
  printf 'MULTICA_Z_WORKSPACE_ID=%s\n' "$MULTICA_Z_WORKSPACE_ID" >> "$LANE_RUNTIME_ENV"
  log "workspace $MULTICA_Z_WS_SLUG = $MULTICA_Z_WORKSPACE_ID"
fi

# ---------------------------------------------------------------------------
# Phase 9 — lane CLI profile + daemon
# ---------------------------------------------------------------------------
log "phase 9: lane profile '$MULTICA_Z_PROFILE' + daemon"

MC_CLI="$MC_REL/bin/multica"
export HOME="$LANE_HOME"
mkdir -p "$LANE_HOME/.multica/profiles/$MULTICA_Z_PROFILE"

# The deploy itself may run inside a daemon-managed task (this is how the team
# runs deploys). That context's environment carries MULTICA_SERVER_URL,
# MULTICA_TOKEN and MULTICA_WORKSPACE_ID pointing at the LIVE control plane,
# which would silently override the lane profile on any flagless call
# (resolution order: --server-url flag > MULTICA_SERVER_URL env > profile
# config), and the task identity triggers the "login is not available inside
# a daemon-managed task" guard. lane-cli.sh strips every MULTICA_* variable
# and runs from a neutral CWD with HOME already the lane home.
mc() { "$SCRIPT_DIR/lane-cli.sh" "$@"; }

mc --profile "$MULTICA_Z_PROFILE" --server-url "$MC_URL" login --token "$MULTICA_Z_PAT" >/dev/null
mc --profile "$MULTICA_Z_PROFILE" config set workspace_id "$MULTICA_Z_WORKSPACE_ID" >/dev/null 2>&1 || true

# Keep the daemon env in sync with the runtime workspace id (phase 8 may have
# just minted it on first run).
umask 077
{
  echo "MULTICA_WORKSPACES_ROOT=$MULTICA_Z_WORKSPACES_ROOT"
  echo "MULTICA_WORKSPACE_ID=$MULTICA_Z_WORKSPACE_ID"
} > "$LANE_ROOT/data/multica-daemon-z.env"
umask 022

systemctl --user enable --now "$MULTICA_DAEMON_Z_UNIT" >/dev/null 2>&1 || true
systemctl --user restart "$MULTICA_DAEMON_Z_UNIT"

# ---------------------------------------------------------------------------
# Phase 9b — dsh runtime profile (optional; needs a bundle source)
# ---------------------------------------------------------------------------
# The daemon registers a dsh runtime only when
# $LANE_HOME/.dsh/profiles/multica exists and its manifest names
# @multica-ai/dsh-runtime — the same check as the daemon's own probe
# (server/internal/daemon/dsh_profile.go). That bridge package is private
# (multica#6936): it is on no registry, and the only local copy (a link:
# target under /tmp) was deleted, so the LIVE dsh-x daemon skips dsh today
# with the same probe error. The lane ships the same way until a bundle
# source exists. Set DSH_Z_RUNTIME_BUNDLE (npm spec, directory or tarball)
# and rerun to install; the deploy can retry, the daemon's own
# MULTICA_DSH_PROFILE_BUNDLE auto-install cannot (once per daemon lifetime).
# The spec itself is never echoed: an npm spec may carry credentials.
log "phase 9b: dsh runtime profile"

DSH_BIN="$(command -v dsh 2>/dev/null || true)"
LANE_DSH_PROFILE="$LANE_HOME/.dsh/profiles/multica"
dsh_profile_names_runtime() {
  [ -f "$LANE_DSH_PROFILE/package.json" ] || return 1
  node -e 'const p=require(process.argv[1]);
    const dep=(p.dependencies||{})["@multica-ai/dsh-runtime"];
    const bundles=((p.dsh||{}).profile||{}).bundles||[];
    process.exit(dep||bundles.includes("@multica-ai/dsh-runtime")?0:1)' \
    "$LANE_DSH_PROFILE/package.json"
}

if dsh_profile_names_runtime; then
  log "dsh runtime profile already installed ($LANE_DSH_PROFILE)"
elif [ -z "${DSH_Z_RUNTIME_BUNDLE:-}" ]; then
  log "skip dsh runtime: @multica-ai/dsh-runtime is unpublished (multica#6936) and DSH_Z_RUNTIME_BUNDLE is unset;"
  log "  the lane daemon registers its other runtimes only (the live dsh-x daemon is in the same state)."
elif [ -z "$DSH_BIN" ]; then
  log "skip dsh runtime: no dsh binary on PATH (DSH_Z_RUNTIME_BUNDLE is set)"
else
  log "installing dsh runtime profile from the DSH_Z_RUNTIME_BUNDLE candidate"
  if HOME="$LANE_HOME" "$DSH_BIN" plugin --profile multica add "$DSH_Z_RUNTIME_BUNDLE" \
    && dsh_profile_names_runtime; then
    log "dsh runtime profile installed -> $LANE_DSH_PROFILE"
  else
    log "WARN: dsh runtime profile install failed; the daemon keeps dsh unregistered (rerun to retry)"
  fi
fi

# ---------------------------------------------------------------------------
# Phase 10 — verify
# ---------------------------------------------------------------------------
log "phase 10: verify"

curl -fsS "$MC_URL/health" | grep -q '"status":"ok"' || die "multica-be z /health"
curl -fsS "$MC_URL/healthz" | grep -q '"status":"ok"' || die "multica-be z /healthz"
curl -fsS "http://127.0.0.1:$MOCT_BE_Z_PORT/team/v1/health" | grep -q '"ok":true' || die "moct-be z /team/v1/health"

INJECT_CODE="$(curl -s -o /dev/null -w '%{http_code}' -G \
  --data-urlencode 'expertId=multica:agent:00000000-0000-0000-0000-0000000000e1' \
  --data-urlencode "workspaceId=multica:ws:$MULTICA_Z_WORKSPACE_ID" \
  --data-urlencode 'taskRef=multica:issue:00000000-0000-0000-0000-0000000000e1' \
  "http://127.0.0.1:$MOCT_BE_Z_PORT/team/v1/memory/inject")"
[ "$INJECT_CODE" = "200" ] || die "moct-be z inject returned $INJECT_CODE (expected 200)"

mc --profile "$MULTICA_Z_PROFILE" agent list >/dev/null \
  || die "lane profile cannot reach multica-be z (agent list failed)"
mc --profile "$MULTICA_Z_PROFILE" issue list >/dev/null \
  || die "lane profile cannot read workspace state from multica-be z (issue list failed)"

log "lane z is up:"
log "  multica-be z   http://127.0.0.1:$MULTICA_BE_Z_PORT  (unit $MULTICA_BE_Z_UNIT)"
log "  postgres       $MULTICA_Z_DB_ROLE @ 127.0.0.1:$MULTICA_Z_DB_PORT/$MULTICA_Z_DB_NAME"
log "  moct-be z      http://127.0.0.1:$MOCT_BE_Z_PORT  (unit $MOCT_BE_Z_UNIT, db $MOCT_Z_DB_PATH)"
log "  lane daemon    profile $MULTICA_Z_PROFILE, home $LANE_HOME (unit $MULTICA_DAEMON_Z_UNIT)"
log "  workspace      $MULTICA_Z_WS_SLUG = $MULTICA_Z_WORKSPACE_ID"
log "done"
